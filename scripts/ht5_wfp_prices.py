"""H-T5, price part: download WFP prices for Benin and write the data sheet.

Usage, from the repository root:
    uv run python scripts/ht5_wfp_prices.py
    uv run python scripts/ht5_wfp_prices.py --no-download
    uv run python scripts/ht5_wfp_prices.py --zone config/zones/zone-a.yaml

Writes docs/data/wfp-prices-benin.md: source, licence, download date,
checksum, then the markets covered for maize, sorghum, cassava and cowpea
with their first and last dates, for all of Benin and for the departments
of the zone profile (default config/zones/zone-a.yaml).
"""

import argparse
import hashlib
import logging
import urllib.request
from datetime import date
from pathlib import Path

import yaml

from agritech.markets.wfp import CROP_COMMODITIES, MarketCoverage, coverage, read_prices

logger = logging.getLogger("ht5_wfp_prices")

DATASET_PAGE = "https://data.humdata.org/dataset/wfp-food-prices-for-benin"
CSV_URL = (
    "https://data.humdata.org/dataset/66c7d54e-0c3b-45e5-9a46-07ea6f195093/resource/"
    "7da1ea0a-56c7-450a-af2c-d477745fc856/download/wfp_food_prices_ben.csv"
)
LICENCE = "CC BY-IGO (Creative Commons Attribution for Intergovernmental Organisations), checked on the HDX page on 2026-11-22"


def download(target: Path) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    logger.info("Downloading %s", CSV_URL)
    with urllib.request.urlopen(CSV_URL, timeout=120) as response:
        target.write_bytes(response.read())


def zone_departments(profile: Path) -> tuple[int, list[str]]:
    """Version of a zone profile and its departments, in file order."""
    data = yaml.safe_load(profile.read_text(encoding="utf-8"))
    return data["zone"]["version"], list(data["communes"])


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def table(rows: list[MarketCoverage]) -> list[str]:
    lines = [
        "| Crop | WFP commodity | Department | Commune | Market | First | Last | Obs. |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    lines += [
        f"| {c.crop} | {c.commodity} | {c.department} | {c.commune} | {c.market} "
        f"| {c.first:%Y-%m} | {c.last:%Y-%m} | {c.observations} |"
        for c in rows
    ]
    return lines


def summary(rows: list[MarketCoverage], since: date) -> list[str]:
    lines = [
        f"| Crop | Markets | Markets with data since {since:%Y-%m} | Last date |",
        "| --- | --- | --- | --- |",
    ]
    for crop in CROP_COMMODITIES:
        mine = [c for c in rows if c.crop == crop]
        markets = {c.market for c in mine}
        recent = {c.market for c in mine if c.last >= since}
        last = max((c.last for c in mine), default=None)
        lines.append(
            f"| {crop} | {len(markets)} | {len(recent)} | {last:%Y-%m-%d} |"
            if last
            else f"| {crop} | 0 | 0 | none |"
        )
    return lines


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--csv", type=Path, default=Path("downloads/wfp_food_prices_ben.csv")
    )
    parser.add_argument(
        "--no-download", action="store_true", help="reuse the local file"
    )
    parser.add_argument(
        "--zone",
        type=Path,
        default=Path("config/zones/zone-a.yaml"),
        help="zone profile whose departments make up the zone section",
    )
    parser.add_argument(
        "--out", type=Path, default=Path("docs/data/wfp-prices-benin.md")
    )
    args = parser.parse_args()

    if args.no_download:
        # The data sheet dates the file itself, not the day it was regenerated.
        downloaded = date.fromtimestamp(args.csv.stat().st_mtime)
    else:
        download(args.csv)
        downloaded = date.today()
    rows = list(read_prices(args.csv))
    all_markets = coverage(rows)
    last_date = max(row.day for row in rows)
    # "Recent": a market that reported in the last twelve months of the file.
    since = date(last_date.year - 1, last_date.month, 1)

    lines = [
        "# Data sheet: WFP food prices, Benin",
        "",
        "Generated by `scripts/ht5_wfp_prices.py`. Do not edit by hand.",
        "",
        "| Field | Value |",
        "| --- | --- |",
        f"| Source | World Food Programme, via HDX: {DATASET_PAGE} |",
        f"| File | {CSV_URL} |",
        f"| Licence | {LICENCE} |",
        f"| Downloaded on | {downloaded:%Y-%m-%d} |",
        f"| SHA-256 | `{sha256(args.csv)}` |",
        f"| Rows | {len(rows)} |",
        f"| Last date in the file | {last_date:%Y-%m-%d} |",
        "| Prices | Retail, XOF per kg, one value per market and month (dated the 15th) |",
        "| Cowpea | No commodity of its own: `Beans (white)` is assumed to be white cowpea |",
        "",
        "## All Benin markets",
        "",
        *summary(all_markets, since),
    ]
    version, departments = zone_departments(args.zone)
    zone = coverage(rows, set(departments))
    lines += [
        "",
        f"## Zone A ({args.zone}, version {version}): {', '.join(departments)}",
        "",
        *summary(zone, since),
        "",
        *table(zone),
    ]
    lines += ["", "## Detail, all markets", "", *table(all_markets), ""]

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    logger.info("Wrote %s (last date %s)", args.out, last_date)


if __name__ == "__main__":
    main()
